package org.linesolver.base.material.catalogue

import kotlinx.serialization.json.*
import org.linesolver.base.material.MaterialRepository
import org.linesolver.base.model.materialFingerprint
import java.time.Instant
import java.time.ZoneOffset
import java.util.Locale
import kotlin.math.abs

/** Offline, deterministic source import. No URL fetching, source repair, or legacy mutation. */
class WebbingCatalogueImport(private val legacy: MaterialRepository, rulesText: String) {
    private val rules = Json.parseToJsonElement(rulesText).jsonObject.also {
        require(it["schema_version"]?.jsonPrimitive?.intOrNull == 1)
    }
    private val aliases = rules.getValue("manufacturer_aliases").jsonObject.entries.associate {
        key(it.key) to it.value.jsonPrimitive.content
    }
    private val decisions = rules.getValue("records").jsonObject
    private val adapter = LegacyV1Catalogue(legacy)
    private val base = adapter.document

    data class Result(val catalogue: ComponentCatalogue, val inventory: JsonObject) {
        fun inventoryText() = CatalogueCodec.canonical(inventory)
        fun report(): String = buildString {
            appendLine("# Webbing catalogue reconciliation")
            appendLine()
            appendLine("Generated by Kotlin from the unchanged supplied source and reviewed reconciliation rules. Counts describe source records unless explicitly labeled products/models. Source claims are retained; no live URL verification or experimental validation is implied.")
            appendLine()
            inventory.getValue("counts").jsonObject.forEach { (k, v) -> appendLine("- ${k.replace('_', ' ')}: $v") }
            appendLine()
            appendLine("All 63 curated model objects, revisions and defaults remain bound to the original JSON. Identical source curves cite an existing model; raw source evidence is retained but no second numerical model is made. Uncertain product/version associations remain separate review records. Independent curves do not establish batches. New models have no upper continuation; the imposed origin is inferred, and one-point laws are provisional only. Unknown mass blocks gravity calculations. MBS is not a working-load limit.")
            appendLine()
            appendLine("## Every source record")
            appendLine()
            appendLine("| ID / source product | Product reconciliation | Dataset status / model | Missing / review / limitations |")
            appendLine("|---|---|---|---|")
            fun safe(s: String) = s.replace("|", "\\|").replace("\n", " ")
            inventory.getValue("records").jsonArray.forEach { element ->
                val r = element.jsonObject
                val warnings = (r.getValue("warnings").jsonArray + r.getValue("restriction").jsonArray).map { it.jsonPrimitive.content }
                appendLine("| ${r["source_id"]} ${safe(r.text("manufacturer") + " / " + r.text("name"))} | ${r.text("match")} → `${r.text("product_id")}` | ${r.text("disposition")} / ${r["model_ids"]} | ${safe(warnings.joinToString("; "))} |")
            }
            appendLine()
            appendLine("## Curated specification comparisons")
            appendLine()
            appendLine("Imported specifications are evidence, never updates to these retained models. Common-force knot comparisons are also retained in inventory-v1.json; mismatching measurements do not establish a batch.")
            appendLine()
            appendLine("| Source ID | Imported mass / (kg/m); applicable MBS / N | Retained model: mass / (kg/m); MBS / N |")
            appendLine("|---|---|---|")
            inventory.getValue("records").jsonArray.forEach { element ->
                val r = element.jsonObject
                val specs = r.getValue("source_specifications").jsonObject
                r.getValue("curated_comparison").jsonArray.forEach { value ->
                    val c = value.jsonObject
                    appendLine("| ${r["source_id"]} | ${specs["density_kg_per_m"]}; ${specs["mbs_n"]} | `${c.text("model_id")}`: ${c["density_kg_per_m"]}; ${c["mbs_n"]} |")
                }
            }
            appendLine()
            appendLine("Full raw fields, original points, notes, dates, URLs, restrictions, per-model comparisons and exclusion reasons are in webbing-catalogue-v1.json and inventory-v1.json. Batch strengths reside in product specifications.information.batch_strength_evidence, keyed to the separate batch record; they are never assigned to unidentified stretch datasets. The checked-in rules name each manual identity/review decision.")
        }
    }

    /** Only case/spacing/punctuation normalization; never removes generation/width/color tokens. */
    private fun key(s: String) = s.lowercase(Locale.ROOT).filter { it.isLetterOrDigit() }
    private fun manufacturer(s: String) = aliases[key(s)] ?: s

    fun matches(brand: String, name: String, products: List<Product> = base.products): List<Product> =
        products.filter { key(it.manufacturer.orEmpty()) == key(manufacturer(brand)) &&
            (listOf(it.name) + it.aliases).any { alias -> key(alias) == key(name) } }.sortedBy { it.id }

    fun import(sourceText: String): Result {
        val source = Json.parseToJsonElement(sourceText).jsonArray.map { it.jsonObject }
        val sourceIds = source.map { requireNotNull(it["id"]?.jsonPrimitive?.intOrNull) { "Source record needs integer id" } }
        require(sourceIds.distinct().size == sourceIds.size) { "Duplicate source ID; import aborted without discarding records" }
        val repeatedNames = source.groupBy { key(manufacturer(it.text("brand"))) to key(it.text("name")) }
            .filterValues { it.size > 1 }.keys
        val products = base.products.associateBy { it.id }.toMutableMap()
        val datasets = base.datasets.toMutableList()
        val models = base.models.toMutableList()
        val versions = base.versions.toMutableList()
        val batches = base.batches.toMutableList()
        val inventory = mutableListOf<JsonObject>()
        val assigned = mutableMapOf<Int, String>()
        val ruleHash = materialFingerprint(CatalogueCodec.canonical(rules))
        for (row in source.sortedBy { it.getValue("id").jsonPrimitive.int }) {
            val id = row.getValue("id").jsonPrimitive.int
            val name = row.text("name"); val brand = row.text("brand")
            require(name.isNotBlank() && brand.isNotBlank()) { "Source $id requires product name and brand" }
            val rule = decisions[id.toString()]?.jsonObject ?: JsonObject(emptyMap())
            require(rule["name"] == null || rule.text("name") == name) { "Stale reconciliation rule for source $id" }
            val notes = row.text("notes")
            val sourceRef = Provenance("data/materials/webbings.json#$id ($brand / $name)", row.optionalText("product_url"),
                note = "Supplied offline evidence; URL not verified by importer. " + notes)
            val warnings = rule.strings("warnings").toMutableList()
            val review = rule.strings("review").toMutableList()
            val candidates = matches(brand, name)
            val ambiguous = rule.strings("ambiguous") + if (candidates.size > 1) candidates.map { it.id } else emptyList()
            val sameSource = rule["same_source_product"]?.jsonPrimitive?.intOrNull
            val target = when {
                ambiguous.isNotEmpty() -> null
                rule.optionalText("target") != null -> rule.text("target").also { require(it in products) { "Unknown reconciliation target: $it" } }
                sameSource != null -> requireNotNull(assigned[sameSource]) { "Copied source must precede alias: $id" }
                candidates.size == 1 -> candidates.single().id
                else -> null
            }
            if (target == null && (key(manufacturer(brand)) to key(name)) in repeatedNames)
                review += "duplicate_unresolved_source_product: distinct source IDs retained without merging"
            if (ambiguous.isNotEmpty()) review += "ambiguous_product_identity: ${ambiguous.joinToString()}"
            val productId = target ?: "webbings:product:$id"
            assigned[id] = productId
            val match = when {
                ambiguous.isNotEmpty() -> "ambiguous_unmerged"
                sameSource != null -> "documented_source_alias"
                target != null && rule.optionalText("target") != null -> "documented_alias"
                target != null -> "manufacturer_name"
                else -> "new_product"
            }
            rule.optionalText("reason")?.let { warnings += it }
            val restrictions = rule.strings("restrictions").toMutableList()
            if (row["manufacturer_not_for_highline"]?.jsonPrimitive?.booleanOrNull == true) {
                restrictions += "Manufacturer restriction in supplied catalogue: NOT FOR HIGHLINE. " +
                    (row.optionalText("manufacturer_not_for_highline_source") ?: "No restriction URL supplied.")
            }
            // Preserve prose restrictions prominently, without deriving prohibitions from MBS or marketing.
            if (Regex("not compatible|does not fit|must be|expert use|exposure|retire|service life|max\\.|pretension", RegexOption.IGNORE_CASE).containsMatchIn(notes))
                restrictions += "Source handling/usage notes: $notes"

            fun quantity(field: String, factor: Double): Double? {
                val v = row[field]?.takeUnless { it is JsonNull } ?: return null
                val n = (v as? JsonPrimitive)?.takeUnless { it.isString }?.doubleOrNull
                return if (n != null && n.isFinite() && n > 0 && (n * factor).isFinite()) n * factor else {
                    review += "invalid_$field: $v"; null
                }
            }
            val density = quantity("weight", .001)
            val declaredMbs = quantity("breakingStrength", 1000.0)
            val applicableMbs = declaredMbs.takeUnless { rule["nominal_mbs"]?.jsonPrimitive?.booleanOrNull == false }
            if (density == null) warnings += "missing_linear_mass: gravity calculations unavailable"
            if (applicableMbs == null) warnings += "missing_applicable_mbs: no rupture strain or upper continuation inferred"
            if (row.optionalText("product_url") == null) warnings += "missing_product_url"
            warnings += "Measurement protocol, calibration, uncertainty and batch association are unknown unless explicitly documented in the source notes."
            if (notes.contains("midpoint", true) || notes.contains("inferred", true) || notes.contains("approx", true))
                warnings += "Source includes approximate/derived information; consult original notes."

            val strengths = mutableListOf<StrengthSpecification>()
            // Only explicit numeric termination phrases. WLL never matches these patterns.
            val strengthPatterns = listOf(
                Regex("(?:3σ )?MBS (80 mm diverter|weblock|sewn loop|linelock ring|after 6 months outdoor exposure) ([0-9.]+) kN"),
                Regex("(loop|TypeX|DLV|sewn-loop|T-loop) MBS ([0-9.]+) kN", RegexOption.IGNORE_CASE),
                Regex("([0-9.]+) kN (sewn loop|Zenlock(?: 1\\.5 wraps| 2x wraps)?|Diamondlock|in weblock after 6 months perma-rig sun exposure)")
            )
            strengthPatterns.forEachIndexed { index, pattern -> pattern.findAll(notes).forEach { found ->
                val label = found.groupValues[if (index == 2) 2 else 1]
                val force = found.groupValues[if (index == 2) 1 else 2].toDouble() * 1000
                strengths += StrengthSpecification(label, force, source = sourceRef, note = "Exact source phrase: ${found.value}")
            } }
            rule["strengths"]?.jsonArray.orEmpty().forEach { s ->
                strengths += StrengthSpecification(s.jsonObject.text("termination"), s.jsonObject.getValue("strength_n").jsonPrimitive.double,
                    source = sourceRef, note = "Reviewed transcription from source notes; no automatic assignment to a rig termination.")
            }
            if (strengths.groupBy { it.termination.lowercase(Locale.ROOT) }.any { (_, s) -> s.map { it.strengthN }.distinct().size > 1 })
                warnings += "conflicting_termination_strength_evidence: all ratings retained independently"
            if (Regex("differ|disagree|conflict|wrong|rejected|supersed", RegexOption.IGNORE_CASE).containsMatchIn(notes))
                warnings += "source_reports_conflict_or_revision: original notes retained for review"

            val versionLabel = Regex("\\bMK\\s*([0-9]+|[IVX]+)\\b", RegexOption.IGNORE_CASE).find(name)?.value
                ?: if (id == 235) "MK II" else null // Explicit version in Rubbit source notes.
            val versionId = versionLabel?.let { "$productId:version:${key(it)}" }
            if (versionId != null && versions.none { it.id == versionId })
                versions += ProductionVersion(versionId, productId, versionLabel, sourceRef)
            val batchInfo = rule["batch"]?.jsonObject
            val batchId = batchInfo?.let { "$productId:batch:${key(it.text("code"))}" }
            if (batchInfo != null) batches += ProductionBatch(batchId!!, productId, batchInfo.text("code"),
                sourceRef.copy(date = batchInfo.optionalText("date")), versionId)
            val information = buildJsonObject {
                put("source_record_id", id)
                put("source_mass_unit", "g/m"); put("mass_to_kg_per_m", .001)
                row["width"]?.let { put("width_mm", it) }; row["thickness"]?.let { put("thickness_mm", it) }
                for (field in listOf("materialType", "materialComposition", "webbing_construction", "active", "date_introduced"))
                    row[field]?.let { put(field, it) }
                row["date_introduced"]?.jsonPrimitive?.longOrNull?.let {
                    put("date_introduced_utc", Instant.ofEpochMilli(it).atOffset(ZoneOffset.UTC).toLocalDate().toString())
                }
                put("declared_strength_n", declaredMbs?.let(::JsonPrimitive) ?: JsonNull)
                if (batchInfo != null) put("batch_strength_evidence", buildJsonObject {
                    put("batch_id", batchId); put("ratings", batchInfo); put("stretch_batch_association", JsonNull)
                })
                put("review_warnings", JsonArray(warnings.map(::JsonPrimitive)))
            }
            val specs = Specifications(densityKgPerM = density, mbsN = applicableMbs, source = sourceRef,
                strengthBasis = if (applicableMbs != null) "Source breakingStrength (kN); configuration in original notes. Not WLL." else "Nominal unassigned; source strength may be batch/termination-specific.",
                terminationStrengths = strengths.distinct(), information = information)
            val oldProduct = products[productId]
            products[productId] = if (oldProduct == null) Product(productId, ProductCategory.webbing, manufacturer(brand), name,
                provenance = listOf(sourceRef), restrictions = restrictions.distinct(), specifications = specs)
            else oldProduct.copy(aliases = (oldProduct.aliases + name).distinct(),
                provenance = (oldProduct.provenance + sourceRef).distinct(),
                restrictions = (oldProduct.restrictions + restrictions).distinct(),
                // Source specifications stay per-dataset evidence; existing model quantities never change.
                specifications = oldProduct.specifications.copy(information = JsonObject(oldProduct.specifications.information +
                    ("source_evidence_$id" to CatalogueCodec.json.encodeToJsonElement(specs)))))

            val cells = row["stretch"]
            val points = mutableListOf<MeasurementPoint>()
            var incomplete = 0
            if (cells != null && cells !is JsonNull) {
                if (cells !is JsonArray) review += "malformed_stretch_array"
                else for (cell in cells) {
                    val obj = cell as? JsonObject
                    if (obj == null) { review += "malformed_stretch_point"; continue }
                    val f = obj["kn"]; val e = obj["percent"]
                    if (f == null || f is JsonNull || e == null || e is JsonNull) { incomplete++; continue }
                    fun number(v: JsonElement) = (v as? JsonPrimitive)?.takeUnless { it.isString }?.doubleOrNull
                    val force = number(f)?.times(1000); val strain = number(e)?.div(100)
                    if (force == null || strain == null || !force.isFinite() || !strain.isFinite()) review += "malformed_numeric_point"
                    else points += MeasurementPoint(strain, force, PointOrigin.supplied)
                }
            }
            if (incomplete > 0) {
                warnings += "incomplete_force_strain_cells: $incomplete (raw cells retained)"
                if (points.isNotEmpty()) review += "incomplete_series_not_partially_promoted"
            }
            if (declaredMbs != null && points.any { it.forceN > declaredMbs }) review += "source_curve_exceeds_declared_strength"
            val comparison = base.models.filter { it.productId == productId }.map { existing ->
                buildJsonObject {
                    put("model_id", existing.id)
                    put("revision", existing.revision)
                    put("density_kg_per_m", existing.specifications.densityKgPerM?.let(::JsonPrimitive) ?: JsonNull)
                    put("mbs_n", existing.specifications.mbsN?.let(::JsonPrimitive) ?: JsonNull)
                    val retained = adapter.points(existing.datasetIds.single()).associateBy { it.forceN }
                    put("common_force_knots", buildJsonArray {
                        for (point in points) retained[point.forceN]?.let { old -> add(buildJsonObject {
                            put("force_n", point.forceN); put("imported_strain", point.strain); put("curated_strain", old.strain)
                        }) }
                    })
                }
            }
            val conflictingSpecs = base.models.filter { it.productId == productId }.any {
                it.specifications.densityKgPerM != density || it.specifications.mbsN != applicableMbs
            }
            if (conflictingSpecs) warnings += "curated_specification_conflict: separate evidence only; curated specifications retained"
            val dataset = MeasurementDataset("webbings:dataset:$id", productId, sourceRef, versionId = versionId,
                originalUnits = SourceUnits("kN", 1000.0, "%", .01),
                procedure = if (id == 261 || id == 242) "ISA standardized stretch, 200 mm gauge, as reported in source notes" else null,
                rawDataStatus = if (sameSource != null) RawDataStatus.derived else RawDataStatus.unknown,
                uncertaintyNotes = warnings.distinct(), conflictFlags = review.distinct(), points = points,
                rawPayload = row)
            datasets += dataset
            val assessment = CatalogueValidation.assess(dataset)
            val usable = assessment.disposition in listOf(DatasetDisposition.monotonic_candidate, DatasetDisposition.provisional_candidate)
            fun equivalent(a: List<MeasurementPoint>, b: List<MeasurementPoint>): Boolean {
                val x = a.filter { it.forceN > 0 && it.strain > 0 }; val y = b.filter { it.forceN > 0 && it.strain > 0 }
                return x.size == y.size && x.zip(y).all { (p, q) -> p.forceN == q.forceN && abs(p.strain - q.strain) <= 1e-14 }
            }
            val duplicates = if (!usable) emptyList() else models.filter { m ->
                m.productId == productId && equivalent(points, m.legacyRecord?.let { adapter.points(m.datasetIds.single()) }
                    ?: datasets.single { it.id == m.datasetIds.single() }.points.orEmpty())
            }
            val modelIds = duplicates.map { it.id }.toMutableList()
            if (usable && duplicates.isEmpty()) {
                val positive = points.filter { it.strain > 0 && it.forceN > 0 }
                val linear = assessment.disposition == DatasetDisposition.provisional_candidate
                val model = CatalogueIdentity.seal(MaterialModel("webbings:model:$id", "1", "", productId,
                    if (linear) LawType.provisional_linear else LawType.pchip, listOf(dataset.id),
                    ModelDomain(positive.last().strain, StrainRange(positive.first().strain, positive.last().strain),
                        continuationNote = "No upper continuation. Origin is imposed; supplied points are not necessarily raw measurements."),
                    versionId = versionId, sourceQuality = if (linear) SourceQuality.provisional else SourceQuality.supplied,
                    curatedDefault = models.none { it.productId == productId && it.curatedDefault },
                    fitDescription = if (linear) "Provisional T=EA*strain; EA=F_ref/strain_ref. Only 0..reference strain; not a measured full curve."
                        else "Existing Kotlin PCHIP with analytic elastic energy; imposed zero origin, supplied ordered knots, no upper continuation.",
                    specifications = specs), listOf(dataset))
                models += model; modelIds += model.id
            }
            inventory += buildJsonObject {
                put("source_id", id); put("name", name); put("manufacturer", brand); put("product_id", productId)
                put("match", match); put("match_evidence", rule.optionalText("reason") ?: "Exact normalized manufacturer/name including version tokens, or unmatched.")
                put("ambiguous_candidates", JsonArray(ambiguous.map(::JsonPrimitive)))
                put("dataset_id", dataset.id); put("disposition", assessment.disposition.name)
                put("positive_points", points.count { it.strain > 0 && it.forceN > 0 })
                put("model_ids", JsonArray(modelIds.map(::JsonPrimitive)))
                put("reused_curve", duplicates.isNotEmpty())
                put("missing_mass", density == null); put("missing_applicable_mbs", applicableMbs == null)
                put("source_specifications", CatalogueCodec.json.encodeToJsonElement(specs))
                put("curated_comparison", JsonArray(comparison))
                put("restriction", JsonArray(restrictions.map(::JsonPrimitive)))
                put("warnings", JsonArray((warnings + review + assessment.reasons).distinct().map(::JsonPrimitive)))
            }
        }
        val document = base.copy(products = products.values.sortedBy { it.id }, datasets = datasets.sortedBy { it.id },
            models = models.sortedBy { it.id }, versions = versions, batches = batches,
            definitions = base.definitions + products.values.filter { p -> base.products.none { it.id == p.id } }
                .map { ComponentDefinition("${it.id}:component", it.id, it.name) })
        CatalogueValidation.requireValid(document)
        val imported = models.filter { it.legacyRecord == null }
        val counts = buildJsonObject {
            put("source_records", source.size)
            put("source_products", assigned.values.distinct().size)
            put("total_products_including_curated", products.size)
            put("matched_curated_products", assigned.values.toSet().intersect(base.products.map { it.id }.toSet()).size)
            put("new_products_confirmed_unmatched", inventory.count { it.text("match") == "new_product" })
            put("ambiguous_unmerged_products", inventory.count { it.text("match") == "ambiguous_unmerged" })
            for (status in DatasetDisposition.entries.filter { it != DatasetDisposition.external_legacy })
                put(status.name, inventory.count { it.text("disposition") == status.name })
            put("new_nonlinear_models", imported.count { it.type == LawType.pchip })
            put("new_provisional_models", imported.count { it.type == LawType.provisional_linear })
            put("reused_existing_curve_records", inventory.count { it["reused_curve"]?.jsonPrimitive?.boolean == true })
            put("reused_curated_curve_records", inventory.count { row -> row["reused_curve"]?.jsonPrimitive?.boolean == true &&
                row.getValue("model_ids").jsonArray.any { value -> base.models.any { it.id == value.jsonPrimitive.content } } })
            put("legacy_models_unchanged", base.models.size)
            put("total_models", models.size)
            put("missing_mass_records", inventory.count { it["missing_mass"]?.jsonPrimitive?.boolean == true })
            put("missing_applicable_mbs_records", inventory.count { it["missing_applicable_mbs"]?.jsonPrimitive?.boolean == true })
            put("explicit_highline_restrictions", source.count { it["manufacturer_not_for_highline"]?.jsonPrimitive?.booleanOrNull == true })
            put("confirmed_batches", batches.size)
            put("source_curves_exceeding_declared_strength", datasets.count { "source_curve_exceeds_declared_strength" in it.conflictFlags })
            put("curated_specification_conflicts", inventory.count { row -> row.getValue("warnings").jsonArray.any {
                it.jsonPrimitive.content.startsWith("curated_specification_conflict") } })
        }
        return Result(document, buildJsonObject {
            put("schema_version", 1); put("source", "data/materials/webbings.json")
            put("source_sha256", materialFingerprint(sourceText)); put("rules_sha256", ruleHash)
            put("units", "kn × 1000 → N; percent / 100 → strain; weight × 0.001 → kg/m; width/thickness remain explicit mm metadata; date_introduced is Unix milliseconds, not measurement date.")
            put("counts", counts); put("records", JsonArray(inventory))
        })
    }
}

internal fun JsonObject.optionalText(key: String) = (get(key) as? JsonPrimitive)?.contentOrNull?.takeIf { it.isNotBlank() }
internal fun JsonObject.text(key: String) = optionalText(key).orEmpty()
internal fun JsonObject.strings(key: String) = get(key)?.jsonArray.orEmpty().map { it.jsonPrimitive.content }
